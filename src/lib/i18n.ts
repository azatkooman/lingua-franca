export const translations = { en, ru, kk };

const LOCALE_KEY = 'lingua_franca_locale';
const LOCALE_CODES = LOCALES.map((locale) => locale.code);
const INTL_LOCALE: Record<Locale, string> = { en: 'en-GB', ru: 'ru-RU', kk: 'kk-KZ' };
/** The locale for Intl date, time and number formats (English uses the 24-hour en-GB style). */
export const intlLocale = (locale: Locale) => INTL_LOCALE[locale];

const readStoredLocale = (): Locale | null => {
    try {
        const saved = localStorage.getItem(LOCALE_KEY);
        return LOCALE_CODES.includes(saved as Locale) ? saved as Locale : null;
    } catch { return null; }
};

/**
 * Interface language is a per-device preference.
 *
 * It used to call setInterfaceLanguage(), which PATCHes /api/admin/settings. That endpoint
 * requires an operator session, so a listener tapping EN/RU on the home screen got a rejected
 * request and no language change -- and had it succeeded it would have switched the interface
 * for every device in the building, which is not what a listener is asking for.
 *
 * The server's interfaceLanguage, set in Admin as "Default language for phones", remains the
 * default for a device that has not chosen one.
 */
let currentLocale: Locale = readStoredLocale() ?? 'en';
let serverDefault: Locale = 'en';
let hasDeviceChoice = readStoredLocale() !== null;
const localeListeners = new Set<() => void>();

const applyLocale = (next: Locale) => {
    document.documentElement.lang = next;
    if (next === currentLocale) return;
    currentLocale = next;
    localeListeners.forEach((listener) => listener());
};
applyLocale(currentLocale);

settingsService.subscribe((settings) => {
    serverDefault = LOCALE_CODES.includes(settings.interfaceLanguage as Locale) ? settings.interfaceLanguage as Locale : 'en';
    if (!hasDeviceChoice) applyLocale(serverDefault);
});

export function setDeviceLocale(next: Locale) {
    hasDeviceChoice = true;
    try { localStorage.setItem(LOCALE_KEY, next); }
    catch { /* private browsing: the choice simply does not persist */ }
    applyLocale(next);
}

/** Drops the device override so the operator's configured default applies again. */
export function clearDeviceLocale() {
    hasDeviceChoice = false;
    try { localStorage.removeItem(LOCALE_KEY); } catch { /* nothing to clear */ }
    applyLocale(serverDefault);
}

const subscribeLocale = (onChange: () => void) => {
    localeListeners.add(onChange);
    return () => { localeListeners.delete(onChange); };
};

/**
 * "5–6 Oct 2026" style, in the reader's language. Dates are calendar days stored as
 * YYYY-MM-DD, so they are formatted in UTC to stop a time zone shifting them by a day.
 */
const KK_MONTHS = ['қаңтар', 'ақпан', 'наурыз', 'сәуір', 'мамыр', 'маусым', 'шілде', 'тамыз', 'қыркүйек', 'қазан', 'қараша', 'желтоқсан'];

// Many browsers ship little Kazakh date data and print "2026 M10 8", so Kazakh is spelled
// out by hand: "8–10 қазан 2026", "30 қыркүйек – 2 қазан 2026".
function formatKazakhRange(start: string, end: string) {
    const parse = (value: string) => { const [year, month, day] = value.split('-').map(Number); return { year, month, day }; };
    const from = parse(start);
    const single = (date: typeof from, withYear = true) => `${date.day} ${KK_MONTHS[date.month - 1]}${withYear ? ` ${date.year}` : ''}`;
    if (!end) return single(from);
    const to = parse(end);
    if (from.year !== to.year) return `${single(from)} – ${single(to)}`;
    if (from.month !== to.month) return `${single(from, false)} – ${single(to)}`;
    return `${from.day}–${single(to)}`;
}

export function formatEventDates(startDate: string, endDate: string, locale: Locale) {
    if (!startDate) return '';
    if (locale === 'kk') return formatKazakhRange(startDate, endDate);
    const toDate = (value: string) => new Date(`${value}T00:00:00Z`);
    const format = new Intl.DateTimeFormat(INTL_LOCALE[locale], { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
    if (!endDate) return format.format(toDate(startDate));
    return format.formatRange(toDate(startDate), toDate(endDate));
}

const DURATION_UNITS: Record<Locale, [string, string, string]> = {
    en: ['h', 'min', 's'],
    ru: ['ч', 'мин', 'с'],
    kk: ['сағ', 'мин', 'с'],
};

/** "1 h 05 min", "12 min", "40 s": short, for the dashboard and the recordings list. */
export function formatDuration(totalSeconds: number, locale: Locale) {
    const [hours, minutes, seconds] = DURATION_UNITS[locale];
    const value = Math.max(0, Math.round(totalSeconds));
    const h = Math.floor(value / 3600);
    const m = Math.floor((value % 3600) / 60);
    if (h) return `${h} ${hours} ${String(m).padStart(2, '0')} ${minutes}`;
    if (m) return `${m} ${minutes}`;
    return `${value} ${seconds}`;
}

/** A sentence in a given interface language, for pages that mix languages (the QR poster). */
export function translateFor(locale: Locale, key: TranslationKey) {
    return translations[locale][key] || en[key];
}

export function useTranslation() {
    // An external store rather than component state: the locale lives outside React and
    // several components read it at once.
    const locale = useSyncExternalStore(subscribeLocale, () => currentLocale, () => currentLocale);

    // `vars` fills {placeholders}, so a sentence keeps its own word order in each language.
    // Stable per locale, so components can list it as an effect or callback dependency
    // without re-running that effect on every render.
    const t = useCallback((key: TranslationKey, vars?: Record<string, string | number>): string => {
        const text = translations[locale][key] || en[key] || key;
        if (!vars) return text;
        return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
    }, [locale]);

    return { t, locale, setLocale: setDeviceLocale };
}
